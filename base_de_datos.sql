-- Habilitar extensión de Postgres para encriptar contraseñas
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- 1. Tabla: Nodos del Bracket (Partidos, equipos y goles)
CREATE TABLE public.nodos_bracket (
    id_nodo TEXT PRIMARY KEY,
    nombre_equipo TEXT DEFAULT 'Por definir',
    goles TEXT DEFAULT '_',
    corazones INTEGER DEFAULT 0
);

-- 2. Tabla: Registro de Votos (Anti-spam por IP)
CREATE TABLE public.registro_votos (
    id_voto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_nodo TEXT REFERENCES public.nodos_bracket(id_nodo) ON DELETE CASCADE,
    ip_usuario TEXT NOT NULL,
    creado_el TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    -- Regla de oro: Una misma IP no puede votar dos veces por el mismo nodo
    UNIQUE(id_nodo, ip_usuario)
);

-- 3. Tabla: Credenciales Admin
CREATE TABLE public.credenciales_admin (
    id_admin BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario TEXT UNIQUE NOT NULL,
    clave_hash TEXT NOT NULL
);

-- 4. Tabla: Estado del Torneo (Campeón actual)
CREATE TABLE public.estado_torneo (
    clave TEXT PRIMARY KEY,
    valor TEXT NOT NULL
);



-- ==========================================
-- FUNCIONES DE BASE DE DATOS (RPC)
-- ==========================================

-- Función para verificar de forma 100% segura la contraseña del administrador sin exponerla
CREATE OR REPLACE FUNCTION public.verificar_admin(p_usuario text, p_password text)
RETURNS boolean
SECURITY DEFINER -- Ejecuta con privilegios del creador para poder leer la tabla credenciales_admin
LANGUAGE plpgsql
AS $$
DECLARE
    v_hash text;
BEGIN
    -- Obtener la clave hash correspondiente al usuario
    SELECT clave_hash INTO v_hash FROM public.credenciales_admin WHERE usuario = p_usuario;
    
    IF v_hash IS NULL THEN
        RETURN false;
    END IF;
    
    -- Comparar la contraseña ingresada con el hash usando pgcrypto
    RETURN v_hash = crypt(p_password, v_hash);
END;
$$;


